const assert=require('node:assert/strict');
const rr=require('../round-robin-nassau.js');
const press=require('../round-robin-presses.js');
const players=[{id:'A',courseHandicap:0},{id:'B',courseHandicap:0},{id:'C',courseHandicap:0}];
const holes=Array.from({length:18},(_,i)=>({number:i+1,strokeIndex:i+1,scores:{A:i<2?3:4,B:4,C:4}}));
const [ab,ac,bc]=rr.calculate(players,holes);
assert.equal(ab.front.lead,2);
assert.equal(press.eligible(ab,'front'),false);
assert.equal(press.eligible(bc,'front'),false);
const partial=holes.map((h,i)=>({...h,scores:i<2?h.scores:{}}));
const [ab2,ac2,bc2]=rr.calculate(players,partial);
assert.equal(press.eligible(ab2,'front'),true);
assert.equal(press.eligible(ac2,'front'),true);
assert.equal(press.eligible(bc2,'front'),false);
const p=press.evaluate(ab2,[{segment:'front',startHole:3}])[0];
assert.equal(p.lead,0);
assert.equal(p.closed,false);
assert.equal(press.eligible(ab2,'front',[{segment:'front',startHole:3}]),false);
console.log('Round Robin Nassau press tests passed');
